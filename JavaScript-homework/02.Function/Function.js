// 제미나이와 함께했습니다... 
function welcomeUser(grade, name) {
  const messages = {
    'VIP 회원':'🌟 VIP {name}님, 특별한 혜택이 준비되어 있습니다!',
    '일반 회원': '안녕하세요, {name}님! 즐거운 쇼핑 되세요.'
  }
  return messages[grade] || messages['일반']
}

